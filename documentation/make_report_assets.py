# ------------------------------------------------------------------ tables
def tex(s):
    return str(s).replace("&", "\\&").replace("%", "\\%").replace("$", "\\$").replace("_", "\\_").replace("#", "\\#").replace("→", "$\\rightarrow$")


def table(name, df, cols, fmts, caption, label, align=None, note=None, size="\\small", fit=False, group_first=False):
    align = align or "l" + "r" * (len(cols) - 1)
    lines = [f"\\begin{{table}}[htbp]\\centering{size}", f"\\caption{{{caption}}}\\label{{{label}}}",
             ("\\resizebox{\\linewidth}{!}{%\n" if fit else "") + f"\\begin{{tabular}}{{{align}}}\\toprule", " & ".join(cols) + " \\\\ \\midrule"]
    prev = None
    for _, r in df.iterrows():
        cells = [f(r) for f in fmts]
        if group_first:
            cells[0], prev = ("" if cells[0] == prev else cells[0]), cells[0]
        lines.append(" & ".join(cells) + " \\\\")
    lines.append("\\bottomrule\\end{tabular}" + ("}" if fit else ""))
    if note:
        lines.append(f"\\par\\smallskip\\begin{{minipage}}{{0.92\\linewidth}}\\footnotesize {note}\\end{{minipage}}")
    lines.append("\\end{table}")
    return name, "\n".join(lines)


